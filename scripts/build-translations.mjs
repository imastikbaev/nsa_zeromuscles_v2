import {readdir,readFile,writeFile} from 'node:fs/promises';
const catalog={};
for(const f of (await readdir('lib/i18n')).filter(f=>f.endsWith('.tsv')).sort()) {
  for(const [i,line] of (await readFile(`lib/i18n/${f}`,'utf8')).split('\n').entries()) {
    if(!line.trim())continue;
    const [en,ru,kk,...extra]=line.split('\t');
    if(!en||!ru||!kk||extra.length)throw Error(`Invalid translation: ${f}:${i+1}`);
    if(catalog[en]&&JSON.stringify(catalog[en])!==JSON.stringify([ru,kk]))throw Error(`Conflicting translation: ${en}`);
    catalog[en]=[ru,kk];
  }
}
await writeFile('lib/i18n/catalog.ts', '// Generated by scripts/build-translations.mjs; edit the TSV catalogs.\nexport const catalog: Record<string, readonly [string, string]> = '+JSON.stringify(catalog,null,2)+';\n');
console.log(`${Object.keys(catalog).length} translation entries (EN/RU/KK).`);
